'''
    Author: Aidan Jude

    Regenerate ingest/aor_books.json from AOR's OWN published bibliography.

    Why this exists as a script rather than a hand-typed map: the first
    version of aor_books.json was hand-filled from the directory names and
    left 15 of 35 books as `null`, because "De navigatione" and
    "Voarchadumia" do not name their authors and guessing would have put a
    fabricated citation into an influence graph. Then the bibliography
    turned up on their own downloads page:

        archaeologyofreading.org/downloads/ -> Corpus-January-2019.xlsx
        (37 rows: Author, Title, Short Title, Place, Location, Shelfmark)

    So every author here is AOR's, joined on Short Title. The only
    hand-made part is DIRMAP, which aligns a repo directory to a Short
    Title -- a label alignment, checkable at a glance against the Shelfmark
    column and against the `internal_ref` book ids inside the XML
    (`PrincetonPA6452` for Livy, matching shelfmark `PA6452 .A2 1555q`).

    Two Sammelbände, and they set a real limit:
      Domenichi   = Folger H.a.2, holding Domenichi's Facetie AND
                    Guicciardini's Detti et Fatti
      Walsingham  = RCP 10552-2, holding Historia brevis AND Ypodigma
    A mark in a bound-together volume cannot be attributed to one of its
    works without page ranges, which the page XML does not carry. So the
    first work is primary and the rest go in `co_bound` and get NO edge.
    Guicciardini is therefore a reader-contact we can see and cannot count.

    Beware openpyxl vs a naive XLSX reader here. These sheets are RAGGED --
    empty cells are omitted from the XML rather than emitted blank, so a
    reader that just concatenates <c> elements shifts every value left and
    silently reads the author column as the title. Books-January-2019.xlsx
    puts its author in column 7 with five empty columns before it.

    Run:  python ingest/aor_resolve_books.py    (needs openpyxl + the xlsx)
    In:   cache/aor_xlsx/Corpus-January-2019.xlsx  (fetched if absent)
    Out:  ingest/aor_corpus.csv, ingest/aor_books.json
'''

import csv
import json
import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(os.path.dirname(HERE), "cache", "aor_xlsx")
BASE = "https://archaeologyofreading.org/wp-content/uploads/sites/21/2019/01"
UA = {"User-Agent": "marginalia-corpus/1.0 (personal research; aidanjude2016@gmail.com)"}
SHEETS = ("Corpus-January-2019.xlsx", "Books-January-2019.xlsx",
          "People-January-2019.xlsx", "Locations-January-2019.xlsx")

# repo directory -> AOR Short Title. First entry is primary; the rest are
# co-bound works in the same physical volume.
DIRMAP = {
    "Alexander": ["RCP's Alexander"],
    "Beroald": ["RCP's Beroaldus"],
    "Buchanan_AneDetectioun": ["Princeton's Ane Detectioun"],
    "Buchanan_MariaScotorumRegina": ["Princeton's De Maria Scotorum Regina"],
    "Cardano": ["RCP's Cardano"],
    "Castiglione": ["UCL's Courtier"],
    "Castiglione_Newberry": ["The Newberry's Courtier"],
    "Cicero I": ["RCP's Cicero 1"],
    "Cicero II": ["RCP's Cicero 2"],
    "Columbus": ["BL's Columbus"],
    "Crusius": ["BL's Crusius"],
    "De navigatione": ["CUL's Saa"],
    "Domenichi": ["Folgers's Facetie", "The Folger's Detti et Fatti"],
    "Dorn": ["NYSL's Dorn"],
    "Euclid": ["BL's Euclid"],
    "Freigius": ["Princeton's Paratitla"],
    "Frontinus": ["Harvard's Stratagems"],
    "Livy": ["Princeton's Livy"],
    "Machiavelli": ["Princeton's Art of War"],
    "Maternus": ["UCL's Maternus"],
    "Matthew Paris": ["RCP's Paris"],
    "Melancthon": ["Princeton's Selectarum Declamationum"],
    "Mizauld": ["RCP's Planetologia"],
    "Monmouth": ["ChCh's Monmouth"],
    "Olaus": ["Princeton's Historia de gentibus septentrionalibus"],
    "Ovid": ["RCP's Ovid"],
    "Paracelsus_Baderbuchlin": ["NYSL's Baderbuchlin"],
    "Paracelsus_Meteorum": ["NYSL's Meteorum"],
    "Pliny the Elder": ["RCP's Pliny"],
    "Postel": ["RCP's Postel"],
    "Quintilian": ["RCP's Quintilian"],
    "Smith": ["Princeton's De Recta"],
    "Tusser": ["Princeton's Husbandry"],
    "Voarchadumia": ["BL's Pantheus"],
    "Walsingham": ["RCP's Historia brevis", "RCP's Ypodigma"],
}

KEEP = ["Author", "Title", "Short Title", "Place of publication", "Location", "Shelfmark"]

NOTE = ("Generated by ingest/aor_resolve_books.py from AOR's own published "
        "bibliography (Corpus-January-2019.xlsx, archaeologyofreading.org/downloads/), "
        "joined on Short Title. `author` is THEIRS, never inferred from the directory "
        "name. Where a directory is a Sammelband holding more than one work, the first "
        "is primary and the rest are in co_bound -- marks cannot be attributed between "
        "co-bound works without page ranges, so co_bound authors get NO edge.")


def fetch_sheets():
    os.makedirs(CACHE, exist_ok=True)
    for name in SHEETS:
        p = os.path.join(CACHE, name)
        if os.path.exists(p) and os.path.getsize(p) > 5000:
            continue
        req = urllib.request.Request(f"{BASE}/{name}", headers=UA)
        open(p, "wb").write(urllib.request.urlopen(req, timeout=60).read())
    return CACHE


def sheet_rows(path):
    import openpyxl
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True).worksheets[0]
    rows = [[("" if c is None else str(c).strip()) for c in r] for r in ws.iter_rows(values_only=True)]
    return [r for r in rows if any(r)]


def main():
    fetch_sheets()
    rows = sheet_rows(os.path.join(CACHE, "Corpus-January-2019.xlsx"))
    recs = [dict(zip(rows[0], r)) for r in rows[1:] if r[0] or r[1]]

    with open(os.path.join(HERE, "aor_corpus.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=KEEP)
        w.writeheader()
        for r in recs:
            w.writerow({k: r.get(k, "") for k in KEEP})

    by_st = {r["Short Title"]: r for r in recs}
    missing = [s for v in DIRMAP.values() for s in v if s not in by_st]
    if missing:
        raise RuntimeError(f"Short Titles absent from AOR's bibliography: {missing} -- "
                           f"the spreadsheet changed; re-align DIRMAP, do not guess.")

    out = {"_note": NOTE}
    for d, sts in DIRMAP.items():
        p = by_st[sts[0]]
        out[d] = dict(author=p["Author"], title=p["Title"], short_title=p["Short Title"],
                      shelfmark=p["Shelfmark"], location=p["Location"],
                      co_bound=[dict(author=by_st[s]["Author"], short_title=s) for s in sts[1:]])
    json.dump(out, open(os.path.join(HERE, "aor_books.json"), "w"), indent=1, ensure_ascii=False)
    res = [k for k in out if not k.startswith("_")]
    print(f"{len(recs)} bibliography rows -> {len(res)} directories resolved, "
          f"{len({out[k]['author'] for k in res})} distinct authors")


if __name__ == "__main__":
    main()
